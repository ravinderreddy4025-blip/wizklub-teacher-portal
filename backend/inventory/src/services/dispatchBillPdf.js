const PDFDocument = require('pdfkit');
const { drawPdfBrandHeader } = require('../utils/brandLogo');

const BRAND_ORANGE = '#F7941D';
const BRAND_DEEP = '#1A1A2E';
const MUTED = '#64748B';
const BORDER = '#E2E8F0';

function formatDate(date) {
  return new Date(date).toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });
}

function drawHeader(doc, consignmentNo) {
  drawPdfBrandHeader(doc, {
    rightTitle: 'DISPATCH CHALLAN',
    rightSubtitle: `Consignment: ${consignmentNo || '—'}`,
  });
}

function drawMetaBlock(doc, rows, x, y, width) {
  let cursorY = y;
  rows.forEach(([label, value]) => {
    doc.fillColor(MUTED).font('Helvetica').fontSize(8).text(label.toUpperCase(), x, cursorY, { width });
    doc.fillColor(BRAND_DEEP).font('Helvetica-Bold').fontSize(10).text(value || '—', x, cursorY + 11, { width });
    cursorY += 34;
  });
  return cursorY;
}

function drawItemsTable(doc, items, startY) {
  const tableTop = startY;
  const colKit = 50;
  const colQty = 260;
  const colComponent = 310;
  const colDispatch = 470;
  const rowHeight = 26;
  const headerHeight = 28;

  doc.rect(50, tableTop, doc.page.width - 100, headerHeight).fill('#FFF8F0');
  doc.fillColor(BRAND_ORANGE).font('Helvetica-Bold').fontSize(8);
  doc.text('KIT / DESCRIPTION', colKit + 8, tableTop + 9);
  doc.text('QTY', colQty, tableTop + 9);
  doc.text('COMPONENT ID', colComponent, tableTop + 9);
  doc.text('DISPATCH ID', colDispatch, tableTop + 9);

  let y = tableTop + headerHeight;
  items.forEach((item, index) => {
    const bg = index % 2 === 0 ? '#FFFFFF' : '#FAFAFA';
    doc.rect(50, y, doc.page.width - 100, rowHeight).fill(bg);
    doc.fillColor(BRAND_DEEP).font('Helvetica-Bold').fontSize(9).text(item.kitName, colKit + 8, y + 8, { width: 195 });
    doc.font('Helvetica-Bold').text(String(item.quantity), colQty, y + 8);
    doc.font('Helvetica').fontSize(8).fillColor('#334155').text(item.componentId, colComponent, y + 8, { width: 150 });
    doc.text(item.dispatchId, colDispatch, y + 8, { width: 90 });
    y += rowHeight;
  });

  doc.strokeColor(BORDER).lineWidth(1).rect(50, tableTop, doc.page.width - 100, y - tableTop).stroke();
  return y + 16;
}

/**
 * @param {object} bill
 * @param {string} bill.consignmentNo
 * @param {string} bill.schoolName
 * @param {string} bill.schoolCode
 * @param {string} bill.divisionName
 * @param {string} bill.category
 * @param {string} bill.amName
 * @param {string} [bill.authorizedBy]
 * @param {Date|string} bill.authorizedAt
 * @param {Array<{kitName:string,quantity:number,componentId:string,dispatchId:string}>} bill.items
 */
function generateDispatchBillPdf(bill) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];

    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    drawHeader(doc, bill.consignmentNo);

    const leftY = drawMetaBlock(doc, [
      ['Dispatch To', bill.schoolName],
      ['School ID', bill.schoolCode],
      ['Division', bill.divisionName],
    ], 50, doc.y, 240);

    drawMetaBlock(doc, [
      ['Category', bill.category],
      ['Account Manager', bill.amName || '—'],
      ['Authorized On', formatDate(bill.authorizedAt)],
    ], 320, doc.y - 102, 225);

    doc.y = Math.max(leftY, doc.y) + 8;
    doc.fillColor(BRAND_DEEP).font('Helvetica-Bold').fontSize(11).text('Line Items', 50, doc.y);
    doc.y += 18;

    const afterTableY = drawItemsTable(doc, bill.items, doc.y);

    const totalQty = bill.items.reduce((sum, item) => sum + Number(item.quantity || 0), 0);
    doc.fillColor(BRAND_DEEP).font('Helvetica-Bold').fontSize(10)
      .text(`Total kits dispatched: ${bill.items.length} line(s) · Total quantity: ${totalQty}`, 50, afterTableY);

    doc.y = afterTableY + 36;
    doc.strokeColor(BORDER).moveTo(50, doc.y).lineTo(doc.page.width - 50, doc.y).stroke();
    doc.y += 14;

    doc.fillColor(MUTED).font('Helvetica').fontSize(8)
      .text('This dispatch challan is system-generated by WizKlub Inventory. Please retain for audit and receipt confirmation.', 50, doc.y, {
        width: doc.page.width - 100,
        align: 'left',
      });

    if (bill.authorizedBy) {
      doc.y += 28;
      doc.fillColor(BRAND_DEEP).font('Helvetica-Bold').fontSize(9).text(`Authorized by: ${bill.authorizedBy}`, 50, doc.y);
    }

    doc.y = doc.page.height - 72;
    doc.fillColor(MUTED).font('Helvetica').fontSize(8)
      .text('WizKlub Operations · helpdesk.scholarbridge@gmail.com', 50, doc.y, { align: 'center', width: doc.page.width - 100 });

    doc.end();
  });
}

function safePdfFilename(value, fallback) {
  const cleaned = String(value || fallback || 'invoice').replace(/[^\w.-]+/g, '_');
  return `WizKlub-Dispatch-${cleaned}.pdf`;
}

async function generateDispatchInvoicePdf(dispatchId) {
  const Dispatch = require('../models/Dispatch');
  const { formatSchoolDisplayName } = require('../utils/schoolName');
  const { getDivisionManager } = require('../utils/divisionManager');

  const dispatch = await Dispatch.findById(dispatchId)
    .populate({ path: 'school', populate: { path: 'divisionId' } })
    .populate('kit')
    .populate('reportingManager')
    .populate('dispatchedBy');

  if (!dispatch) {
    const error = new Error('Dispatch not found');
    error.status = 404;
    throw error;
  }

  const school = dispatch.school;
  const schoolId = school?._id || dispatch.school;
  const tracking = String(dispatch.consignmentNo || dispatch.trackingId || '').trim();

  let lines = [];
  if (tracking) {
    lines = await Dispatch.find({
      school: schoolId,
      $or: [{ consignmentNo: tracking }, { trackingId: tracking }],
    })
      .populate('kit')
      .sort({ createdAt: 1 });
  }
  if (!lines.length) lines = [dispatch];

  const items = lines.map((line) => ({
    kitName: line.kit?.name || 'Kit',
    quantity: line.quantity,
    componentId: line.componentId || line.kitId || '—',
    dispatchId: line.dispatchId || String(line._id),
  }));

  const am = dispatch.reportingManager
    || await getDivisionManager(school?.divisionId?._id || school?.divisionId);

  const buffer = await generateDispatchBillPdf({
    consignmentNo: tracking || dispatch.dispatchId || '—',
    schoolName: formatSchoolDisplayName(school?.name),
    schoolCode: school?.code || '—',
    divisionName: school?.divisionId?.name || '—',
    category: dispatch.category || 'New Dispatch',
    amName: am?.name,
    authorizedBy: dispatch.dispatchedBy?.name,
    authorizedAt: dispatch.dispatchedAt || dispatch.createdAt,
    items,
  });

  return {
    buffer,
    filename: safePdfFilename(tracking || dispatch.dispatchId, dispatchId),
    dispatch,
  };
}

function sendInvoicePdf(res, buffer, filename) {
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
  res.send(buffer);
}

module.exports = { generateDispatchBillPdf, generateDispatchInvoicePdf, sendInvoicePdf };
